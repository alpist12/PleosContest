package ai.pleos.contest.ui

import androidx.compose.foundation.layout.*
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.verticalScroll
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.runtime.saveable.rememberSaveable
import androidx.compose.ui.Modifier
import androidx.compose.ui.Alignment
import androidx.compose.ui.unit.dp
import ai.pleos.contest.data.TripStore
import ai.pleos.contest.domain.*

@Composable
internal fun RecommendationScreen(initial: PackingProfile, warning: String?, vehicle: Boolean = false, onBack: () -> Unit) {
    val muted = if (vehicle) Tok.muted else MTok.muted
    val warningColor = if (vehicle) Tok.warn else MTok.amber
    val accent = if (vehicle) Tok.accent else MTok.sky
    var activity by rememberSaveable { mutableStateOf(initial.activity) }
    var nights by rememberSaveable { mutableIntStateOf(initial.nights) }
    var adults by rememberSaveable { mutableIntStateOf(initial.adults) }
    var children by rememberSaveable { mutableIntStateOf(initial.children) }
    var infants by rememberSaveable { mutableIntStateOf(initial.infants) }
    val profile = PackingProfile(activity, nights, adults, children, infants)
    var generated by rememberSaveable { mutableStateOf(true) }
    var selected by rememberSaveable { mutableStateOf(emptyList<String>()) }
    var message by rememberSaveable { mutableStateOf("") }
    val trip = TripStore.trip
    val suggestions = PackingRecommendations.suggest(profile, trip.items)
    val editable = trip.status in setOf(TripStatus.DRAFT, TripStatus.PREPARING, TripStatus.DEPARTURE_CHECK)
    fun changed() { generated = false; selected = emptyList(); message = "" }
    Box(Modifier.fillMaxSize(), contentAlignment = Alignment.TopCenter) {
    Column(Modifier.widthIn(max = 760.dp).fillMaxWidth().verticalScroll(rememberScrollState()).padding(20.dp), verticalArrangement = Arrangement.spacedBy(12.dp)) {
        TextButton(onClick = onBack) { Text("돌아가기") }
        Text("우리 가족 준비물 추천", style = MaterialTheme.typography.titleLarge)
        Text("활동·기간·인원에 맞춰 계산해요. 날씨 정보나 생성형 AI 응답을 사용한 추천은 아니에요.", color = muted)
        warning?.let { Text(it, color = warningColor) }
        PackingProfile.activities.chunked(2).forEach { pair -> Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            pair.forEach { type -> FilterChip(selected = activity == type, onClick = { activity = type; changed() }, label = { Text(type) }) }
        } }
        Counter("숙박", nights, 0, 14, "박") { nights = it; changed() }
        Counter("성인", adults, 1, minOf(12, 20 - children - infants), "명") { adults = it; changed() }
        Counter("어린이", children, 0, minOf(12, 20 - adults - infants), "명") { children = it; changed() }
        Counter("영유아", infants, 0, minOf(6, 20 - adults - children), "명") { infants = it; changed() }
        Text("${nights + 1}일 · 총 ${profile.people}명 / 수량은 기본 기준이며 실제 필요량에 맞게 편집해 주세요.", color = muted)
        OutlinedButton(onClick = {
            TripStore.savePackingProfile(profile); generated = true
            selected = suggestions.map { it.key }; message = ""
        }, modifier = Modifier.fillMaxWidth().heightIn(min = 56.dp)) { Text("이 조건으로 추천 보기") }
        if (generated) {
            Text("기존 목록에 없는 ${suggestions.size}가지", style = MaterialTheme.typography.titleMedium)
            Text("이미 등록되거나 제외한 물건은 다시 추가하지 않아요. 기존 물건의 수량은 자동 변경하지 않습니다.", color = muted)
            suggestions.forEach { row ->
                Row(Modifier.fillMaxWidth()) {
                    Checkbox(row.key in selected, { checked -> selected = if (checked) (selected + row.key).distinct() else selected - row.key })
                    Column(Modifier.weight(1f).padding(vertical = 10.dp)) {
                        Text(row.label)
                        Text(row.reason, style = MaterialTheme.typography.bodySmall, color = muted)
                    }
                }
                HorizontalDivider(color = if (vehicle) Tok.hairline else MTok.lineSoft)
            }
            if (!editable) Text("지금은 여행 진행 또는 종료 단계예요. 준비 단계에서만 물건을 추가할 수 있어요.", color = warningColor)
            Button(enabled = editable && suggestions.any { it.key in selected }, onClick = {
                runCatching { TripStore.addRecommendations(profile, selected.toSet()) }
                    .onSuccess { message = "${it}가지를 추가했어요. 담당자와 수량은 준비물 화면에서 편집해 주세요."; selected = emptyList() }
                    .onFailure { message = it.message ?: "준비물을 추가하지 못했어요" }
            }, modifier = Modifier.fillMaxWidth().heightIn(min = 56.dp)) { Text("선택한 ${suggestions.count { it.key in selected }}가지 추가") }
        }
        if (message.isNotEmpty()) Text(message, color = accent)
        if (TripStore.canUndo) TextButton(onClick = { TripStore.undo(); message = "최근 변경을 되돌렸어요" }) { Text("최근 변경 되돌리기") }
    }
    }
}

@Composable
private fun Counter(label: String, value: Int, min: Int, max: Int, unit: String, change: (Int) -> Unit) {
    Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween) {
        Text("$label $value$unit", Modifier.weight(1f).padding(top = 14.dp))
        OutlinedButton(enabled = value > min, onClick = { change(value - 1) }, modifier = Modifier.sizeIn(minWidth = 56.dp, minHeight = 56.dp)) { Text("$label −") }
        Spacer(Modifier.width(8.dp))
        OutlinedButton(enabled = value < max, onClick = { change(value + 1) }, modifier = Modifier.sizeIn(minWidth = 56.dp, minHeight = 56.dp)) { Text("$label +") }
    }
}
